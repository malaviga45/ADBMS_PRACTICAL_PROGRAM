CREATE TABLE STUDENT_DATA (
    SID NUMBER,
    SNAME VARCHAR2(30),
    COURSE_ID NUMBER
);

CREATE TABLE COURSE_DATA (
    COURSE_ID NUMBER,
    COURSE_NAME VARCHAR2(30)
);

