-- INNER JOIN
SELECT S.SID, S.SNAME, C.COURSE_NAME
FROM STUDENT_DATA S
INNER JOIN COURSE_DATA C
ON S.COURSE_ID = C.COURSE_ID;

-- LEFT JOIN
SELECT S.SID, S.SNAME, C.COURSE_NAME
FROM STUDENT_DATA S
LEFT JOIN COURSE_DATA C
ON S.COURSE_ID = C.COURSE_ID;

-- RIGHT JOIN
SELECT S.SID, S.SNAME, C.COURSE_NAME
FROM STUDENT_DATA S
RIGHT JOIN COURSE_DATA C
ON S.COURSE_ID = C.COURSE_ID;
